from __future__ import annotations

from pathlib import Path

import pytest
import yaml

from pvc.errors import PvcError
from pvc.inventory import build_inventory, group_name, write_inventory
from pvc.manifest import resolve_service
from pvc.roles import KNOWN_ROLES

from .conftest import BLOG_RAW

KEY = Path("/home/me/.ssh/pvc/blog")


@pytest.fixture
def blog(site):
    return resolve_service(site, "blog", BLOG_RAW)


TERRAFORM_HOSTS = {
    "db": {"name": "blog-db", "ip": "172.20.30.21", "vm_id": 1101, "node": "pve1"},
    "app": {"name": "blog-app", "ip": "172.20.30.55", "vm_id": 1102, "node": "pve2"},
}


def test_hosts_carry_address_identity_and_manifest_vars(site, blog):
    inventory = build_inventory(site, blog, TERRAFORM_HOSTS, KEY)["all"]

    db = inventory["hosts"]["blog-db"]
    assert db["ansible_host"] == "172.20.30.21"
    assert db["host_key"] == "db"
    assert db["sys_hostname"] == "blog-db"
    assert db["compose_stack"] == "postgres"

    # DHCP host: the address comes from Terraform, not the manifest.
    assert inventory["hosts"]["blog-app"]["ansible_host"] == "172.20.30.55"


def test_service_host_and_role_groups(site, blog):
    children = build_inventory(site, blog, TERRAFORM_HOSTS, KEY)["all"]["children"]

    assert set(children["svc_blog"]["hosts"]) == {"blog-db", "blog-app"}
    assert set(children["svc_blog_db"]["hosts"]) == {"blog-db"}
    assert set(children["role_base"]["hosts"]) == {"blog-db", "blog-app"}
    assert set(children["role_nginx"]["hosts"]) == {"blog-app"}
    # compose implies docker, so both hosts with compose or docker are in role_docker.
    assert set(children["role_docker"]["hosts"]) == {"blog-db", "blog-app"}
    assert set(children["role_compose"]["hosts"]) == {"blog-db"}
    assert set(children["role_node_exporter"]["hosts"]) == {"blog-db"}


def test_every_role_group_exists_even_when_empty(site, blog):
    """site.yml targets role_<name>; a missing group would only produce a warning, but keep runs quiet."""
    children = build_inventory(site, blog, TERRAFORM_HOSTS, KEY)["all"]["children"]

    for role in KNOWN_ROLES:
        assert f"role_{role}" in children
    assert children["role_kubernetes"]["hosts"] == {}


def test_connection_vars_use_the_service_key_and_final_ssh_port(site, blog):
    variables = build_inventory(site, blog, TERRAFORM_HOSTS, KEY)["all"]["vars"]

    assert variables["ansible_user"] == "devops"
    assert variables["ansible_port"] == 4224 == variables["ssh_port"]
    assert variables["ansible_ssh_private_key_file"] == str(KEY)
    assert variables["ansible_become_password"] == "{{ vault_devops_password }}"
    assert variables["service_name"] == "blog"
    assert variables["service_dir"].endswith("services/blog")
    # site.yml ansible_vars are included, over the built-in defaults.
    assert variables["node_exporter_ufw_from"] == "172.20.30.0/24"
    assert variables["ansible_python_interpreter"] == "/usr/bin/python3"


def test_static_host_falls_back_to_its_manifest_address(site, blog):
    only_app = {"app": TERRAFORM_HOSTS["app"]}

    inventory = build_inventory(site, blog, only_app, KEY)["all"]

    assert inventory["hosts"]["blog-db"]["ansible_host"] == "172.20.30.21"


def test_dhcp_host_without_a_reported_address_is_an_error(site, blog):
    with pytest.raises(PvcError, match="No IP address"):
        build_inventory(site, blog, {"db": TERRAFORM_HOSTS["db"]}, KEY)

    with pytest.raises(PvcError, match="No IP address"):
        build_inventory(site, blog, {**TERRAFORM_HOSTS, "app": {**TERRAFORM_HOSTS["app"], "ip": ""}}, KEY)


def test_names_with_hyphens_become_valid_group_names(site):
    service = resolve_service(site, "arr-stack", {"hosts": {"web-1": {"vm_id": 1600, "node": "pve1"}}})
    inventory = build_inventory(
        site, service, {"web-1": {"ip": "10.0.0.5", "name": "arr-stack-web-1"}}, KEY
    )["all"]

    assert "svc_arr_stack" in inventory["children"]
    assert "svc_arr_stack_web_1" in inventory["children"]
    assert "arr-stack-web-1" in inventory["hosts"]
    assert group_name("role", "node_exporter") == "role_node_exporter"


def test_written_inventory_is_loadable_yaml_with_a_do_not_edit_header(site, blog, project):
    inventory = build_inventory(site, blog, TERRAFORM_HOSTS, KEY)
    (project / "services" / "blog").mkdir()

    path = write_inventory(inventory, "blog")

    text = path.read_text()
    assert text.startswith("# Generated by pvc")
    assert yaml.safe_load(text) == inventory
